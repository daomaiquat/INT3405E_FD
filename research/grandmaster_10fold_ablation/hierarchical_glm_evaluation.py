"""Compare new GLM branches with the existing hierarchical stack."""

import numpy as np
from sklearn.metrics import roc_auc_score

from run_meta_improvements import score_variants


CANDIDATE_NAMES = ("hierarchical_glm", "hierarchical_glm_interactions")
BASELINE_NAME = "current_hierarchy"
SCREEN_L2 = 1e-5


def _finite_matrix(values, shape, name):
    matrix = np.asarray(values, dtype=np.float64)
    if matrix.shape != shape or not np.isfinite(matrix).all():
        raise ValueError(f"Expected finite {name} logits with shape {shape}.")
    return matrix


def _pair_weighted(fold_results, field):
    weights = [item["positive_negative_pairs"] for item in fold_results]
    return {
        name: float(np.average([item[field][name] for item in fold_results], weights=weights))
        for name in fold_results[0][field]
    }


def evaluate_architecture(nb, meta, training, score_folds, labels, holdout_labels, folds, new_oof, new_holdout_folds):
    """Score the historical holdout ensemble and each isolated development fold.

    Each candidate is a single added meta feature. The ensemble uses the
    original development/holdout roles. Screening trains each meta model on
    the old holdout logits generated by the same base models that score its
    development fold, keeping the screening labels out of both fits. Screening
    uses a fixed penalty because historical tuning used global OOF features.
    """
    labels = np.asarray(labels, dtype=np.float64)
    holdout_labels = np.asarray(holdout_labels, dtype=np.float64)
    for values in (labels, holdout_labels):
        if values.ndim != 1 or not np.array_equal(np.unique(values), [0, 1]):
            raise ValueError("Each label vector must contain both binary classes.")

    l2s = np.asarray(meta["baseline_meta_l2_by_fold"], dtype=np.float64)
    count = len(folds)
    if count < 2 or len(score_folds) != count or len(new_holdout_folds) != count:
        raise ValueError("Expected matching development and holdout folds.")
    if l2s.shape != (count,) or not np.isfinite(l2s).all() or (l2s < 0).any():
        raise ValueError("Expected one finite nonnegative L2 penalty per fold.")

    training = np.asarray(training, dtype=np.float64)
    if (training.ndim != 2 or len(training) != len(labels) or training.shape[1] == 0
            or not np.isfinite(training).all()):
        raise ValueError("Expected one finite baseline OOF row per development label.")
    new_oof = _finite_matrix(new_oof, (len(labels), len(CANDIDATE_NAMES)), "candidate OOF")
    score_folds = [_finite_matrix(scores, (len(holdout_labels), training.shape[1]), "baseline holdout")
                   for scores in score_folds]
    new_holdout_folds = [_finite_matrix(scores, (len(holdout_labels), len(CANDIDATE_NAMES)), "candidate holdout")
                         for scores in new_holdout_folds]

    fold_results = []
    partitions = []
    held_counts = np.zeros(len(labels), dtype=np.int32)
    for fold, fit, held in folds:
        fit, held = np.asarray(fit), np.asarray(held)
        for indices in (fit, held):
            if (indices.ndim != 1 or not len(indices) or indices.dtype.kind not in "iu"
                    or (indices < 0).any() or (indices >= len(labels)).any()):
                raise ValueError("Expected valid one-dimensional development fold indices.")
        fit, held = fit.astype(np.intp, copy=False), held.astype(np.intp, copy=False)
        if not np.all(np.bincount(np.concatenate((fit, held)), minlength=len(labels)) == 1):
            raise ValueError("Training and held rows must partition development in every fold.")
        held_counts[held] += 1
        positives = int(labels[held].sum())
        pairs = positives * (len(held) - positives)
        if not pairs:
            raise ValueError("Each held development fold must contain both binary classes.")
        partitions.append((fit, held))
        fold_results.append({
            "fold": int(fold) + 1,
            "rows": len(held),
            "positive_negative_pairs": pairs,
            "roc_auc": {},
            "delta_roc_auc": {},
            "standalone_roc_auc": {},
            "added_logit_weights": {},
        })
    if not np.all(held_counts == 1):
        raise ValueError("Held folds must cover each development row exactly once.")

    fit_stack = nb["_fit_nonneg_l2_weights"]
    link = nb["from_logit_10"]
    mean_baseline = sum(score_folds) / count
    mean_candidates = sum(new_holdout_folds) / count
    predictions = {}
    mean_added_logit_weights = {}
    baseline_fits = []
    columns = dict(zip(CANDIDATE_NAMES, range(len(CANDIDATE_NAMES)), strict=True))
    for name in (BASELINE_NAME, *CANDIDATE_NAMES):
        column = columns.get(name)
        development = training if column is None else np.column_stack((training, new_oof[:, column]))
        mean_holdout = mean_baseline if column is None else np.column_stack((mean_baseline, mean_candidates[:, column]))
        intercepts, coefficients = [], []
        for index, ((fit, held), l2, report) in enumerate(zip(partitions, l2s, fold_results, strict=True)):
            intercept, weights = fit_stack(development[fit], labels[fit], l2)
            if column is None:
                baseline_fits.append((intercept, weights))
            elif weights[-1] == 0.0:
                # At the zero boundary the augmented model reduces to the baseline.
                intercept, baseline_weights = baseline_fits[index]
                weights = np.append(baseline_weights, 0.0)
            intercepts.append(intercept)
            coefficients.append(weights)

            screen_fit = score_folds[index]
            if column is not None:
                screen_fit = np.column_stack((screen_fit, new_holdout_folds[index][:, column]))
                report["standalone_roc_auc"][name] = float(roc_auc_score(labels[held], new_oof[held, column]))
            screen_intercept, screen_weights = fit_stack(screen_fit, holdout_labels, SCREEN_L2)
            if column is not None:
                report["added_logit_weights"][name] = float(screen_weights[-1])
            if column is not None and screen_weights[-1] == 0.0:
                auc = report["roc_auc"][BASELINE_NAME]
            else:
                screen_logits = screen_intercept + development[held] @ screen_weights
                auc = float(roc_auc_score(labels[held], screen_logits))
            report["roc_auc"][name] = auc
            report["delta_roc_auc"][name] = auc - report["roc_auc"][BASELINE_NAME]

        mean_weights = np.mean(coefficients, axis=0)
        if column is not None and mean_weights[-1] == 0.0:
            probabilities = predictions[BASELINE_NAME].copy()
        else:
            probabilities = link(np.mean(intercepts) + mean_holdout @ mean_weights)
        if (probabilities.shape != holdout_labels.shape or not np.isfinite(probabilities).all()
                or ((probabilities < 0) | (probabilities > 1)).any()):
            raise ValueError(f"Invalid holdout probabilities for {name}.")
        predictions[name] = probabilities
        if column is not None:
            mean_added_logit_weights[name] = float(mean_weights[-1])

    additive, interactions = CANDIDATE_NAMES
    contrast = nb["delong_paired_test"](holdout_labels, predictions[interactions], predictions[additive])
    return {
        "predictions": predictions,
        "metrics": score_variants(nb, holdout_labels, predictions),
        "mean_added_logit_weights": mean_added_logit_weights,
        "interactions_vs_additive": {
            "delta_roc_auc": contrast["diff"],
            "ci95_low": contrast["ci_low"],
            "ci95_high": contrast["ci_high"],
            "p_value": contrast["p_value"],
        },
        "fold_screening": {
            "screen_l2": SCREEN_L2,
            "folds": fold_results,
            "pair_weighted_roc_auc": _pair_weighted(fold_results, "roc_auc"),
            "pair_weighted_delta_roc_auc": _pair_weighted(fold_results, "delta_roc_auc"),
            "pair_weighted_standalone_roc_auc": _pair_weighted(fold_results, "standalone_roc_auc"),
        },
    }
